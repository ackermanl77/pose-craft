def app_version() -> str:
    """``__version__`` read from pose_craft/__init__.py without importing the package."""
    with open(os.path.join(ROOT, "pose_craft", "__init__.py"), encoding="utf-8") as handle:
        match = re.search(r'^__version__\s*=\s*"([^"]+)"', handle.read(), re.MULTILINE)
    if not match:
        raise RuntimeError("pose_craft/__init__.py defines no __version__")
    return match.group(1)


def version_tuple(version: str) -> tuple:
    """``"0.1.0"`` -> ``(0, 1, 0, 0)``; each number capped at 16 bits."""
    parts = [min(int(part), 0xFFFF) for part in re.findall(r"\d+", version)[:4]]
    return tuple(parts + [0] * (4 - len(parts)))


def version_file_text(version: str) -> str:
    numbers = version_tuple(version)
    return _VERSION_TEMPLATE.format(numbers=repr(numbers), version=version, publisher=PUBLISHER, product=PRODUCT)


def write_version_file(out_dir: str, version: str = None) -> str:
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "posecraft_version.txt")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(version_file_text(version or app_version()))
    return path


def write_manifest(out_dir: str) -> str:
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "PoseCraft.manifest")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(MANIFEST_XML)
    return path


# ------------------------------------------------------------------ icons


def read_ico(data: bytes) -> dict:
    """{side: (bit count, raw image bytes)} of an .ico (PNG or BMP entries)."""
    _reserved, _kind, count = struct.unpack_from("<HHH", data, 0)
    images = {}
    for i in range(count):
        width, _h, _colors, _res, _planes, bits, size, offset = struct.unpack_from("<BBBBHHII", data, 6 + 16 * i)
        images[256 if width == 0 else width] = (bits, data[offset:offset + size])
    return images


def ico_bytes(images: dict) -> bytes:
    sides = sorted(images)
    header = struct.pack("<HHH", 0, 1, len(sides))
    offset = len(header) + 16 * len(sides)
    entries, blob = b"", b""
    for side in sides:
        bits, raw = images[side]
        byte_side = 0 if side >= 256 else side
        entries += struct.pack("<BBBBHHII", byte_side, byte_side, 0, 0, 1, bits or 32, len(raw), offset)
        offset += len(raw)
        blob += raw
    return header + entries + blob


def _png_at(side: int) -> bytes:
    from PySide6.QtCore import QBuffer, QIODevice, Qt
    from PySide6.QtGui import QImage

    image = QImage(APP_ICON_PNG).scaled(side, side, Qt.AspectRatioMode.IgnoreAspectRatio,
                                        Qt.TransformationMode.SmoothTransformation)
    buffer = QBuffer()
    buffer.open(QIODevice.OpenModeFlag.WriteOnly)
    image.save(buffer, "PNG")
    return bytes(buffer.data())


def add_icon_sizes(path: str = APP_ICON) -> list:
    """Add the missing ICON_SIZES to `path`; returns the sizes added."""
    from PySide6.QtGui import QGuiApplication

    if QGuiApplication.instance() is None:
        os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
        add_icon_sizes._app = QGuiApplication(sys.argv[:1])
    with open(path, "rb") as handle:
        images = read_ico(handle.read())
    added = [side for side in ICON_SIZES if side not in images]
    for side in added:
        images[side] = (32, _png_at(side))
    with open(path, "wb") as handle:
        handle.write(ico_bytes(images))
    return added


if __name__ == "__main__":
    command = sys.argv[1] if len(sys.argv) > 1 else "version"
    if command == "version":
        print(app_version())
    elif command == "icon-sizes":
        print("added", add_icon_sizes() or "nothing")
    else:
        raise SystemExit(f"unknown command {command!r} (version, icon-sizes)")
