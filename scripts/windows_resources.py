"""Windows resources of the packaged PoseCraft.exe (report item K7), written by PoseCraft.spec at build
time into PyInstaller's work folder.

- The version resource (Properties > Details): CompanyName "MELEJ" -- the one publisher name used by
  every project (the installer's AppPublisher too), which should match the future code-signing
  certificate's subject -- and ``pose_craft.__version__``, the single version source.
- The application manifest: PyInstaller's default one (asInvoker, the supportedOS list, longPathAware,
  Common-Controls v6) plus ``activeCodePage`` UTF-8 -- the process's ANSI code page becomes UTF-8, so a
  native library calling the narrow Win32 file APIs (``cv2.imread``, which returned None for a PNG under
  ``Imágenes_test`` on 2026-10-18) opens such paths -- and ``dpiAwareness`` PerMonitorV2 (with the older
  ``dpiAware`` fallback), so the Qt window and native dialogs are sharp on a scaled desktop.
- ``add_icon_sizes()`` (a developer step; the .ico is checked in): adds the 20/24/40/64 px sizes Explorer
  and the taskbar ask for at 125-200 % scaling to ``assets/icon.ico``, drawn with Qt from the 256 px
  ``assets/icon.png``, keeping the existing images byte for byte.

    python scripts/windows_resources.py version     # prints pose_craft.__version__
    python scripts/windows_resources.py icon-sizes  # updates assets/icon.ico

Standard library only, except ``add_icon_sizes()`` (PySide6)."""

