"""Write THIRD_PARTY_NOTICES.md: the license of everything the packaged app bundles.

Run it with the Python of the environment the build uses, after any dependency change:

    build-venv-dml\\Scripts\\python scripts/third_party_notices.py

It lists every installed distribution except development and build-only tools, with the
license texts each one ships in its metadata, then the Python runtime's license, then the
components that don't come from pip (EXTRA below, kept by hand).
"""
from __future__ import annotations

import importlib.metadata as metadata
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "THIRD_PARTY_NOTICES.md"
APP_NAME = "PoseCraft"
SELF = {'posecraft', 'pose-craft'}

# Development and build tools: installed in the environment, never shipped. PyInstaller
# itself stays in the list because its bootloader is part of every packaged app.
BUILD_ONLY = {
    "pip", "setuptools", "wheel", "build", "pyinstaller-hooks-contrib", "altgraph", "pefile",
    "pywin32-ctypes", "pytest", "pytest-xdist", "pytest-timeout", "pytest-cov", "pytest-qt",
    "pytest-playwright", "pytest-base-url", "execnet", "iniconfig", "pluggy", "coverage", "ruff",
    "mypy", "mypy-extensions", "pyright", "nodeenv", "hypothesis", "sortedcontainers", "playwright",
    "pyee", "greenlet", "pip-audit", "pip-tools", "pyproject-hooks", "black", "isort", "flake8",
    "types-requests", "types-pyyaml",
}

LICENSE_FILE = re.compile(r"^(licen[cs]e|copying|notice|authors|copyright)([._-].*)?$", re.IGNORECASE)

EXTRA = """- **MediaPipe Pose Landmarker and Hand Landmarker models** (BlazePose), converted to ONNX and bundled in `models/`. Apache License 2.0, Copyright Google LLC: https://ai.google.dev/edge/mediapipe/solutions/vision/pose_landmarker
- The self-test photo `tests/data/golden/yoga_tree.jpg` is CC0 (public domain).
"""


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _license_name(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    expression = meta.get("License-Expression")
    if expression:
        return expression.strip()
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or []
                   if c.startswith("License ::") and c.strip() != "License :: OSI Approved"]
    if classifiers:
        return "; ".join(dict.fromkeys(classifiers))
    text = (meta.get("License") or "").strip()
    if text and "\n" not in text and len(text) < 80:
        return text
    return "see the license text below"


def _homepage(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    if meta.get("Home-page"):
        return meta["Home-page"].strip()
    for entry in meta.get_all("Project-URL") or []:
        label, _, url = entry.partition(",")
        if label.strip().lower() in {"homepage", "home", "source", "repository", "source code"}:
            return url.strip()
    return ""


def _license_texts(dist: metadata.Distribution) -> list[tuple[str, str]]:
    texts = []
    for file in dist.files or []:
        parts = Path(str(file)).parts
        in_dist_info = any(part.endswith((".dist-info", ".egg-info")) for part in parts)
        if not in_dist_info or not (LICENSE_FILE.match(parts[-1]) or "licenses" in parts):
            continue
        try:
            text = Path(dist.locate_file(file)).read_text(encoding="utf-8", errors="replace").strip()
        except OSError:
            continue
        if text:
            texts.append((parts[-1], text))
    if not texts:
        text = (dist.metadata.get("License") or "").strip()
        if "\n" in text:
            texts.append(("License (from the package metadata)", text))
    return texts


def _block(text: str) -> str:
    return "~~~~text\n" + text.replace("~~~~", "~ ~ ~ ~") + "\n~~~~\n"


def main() -> int:
    seen = set()
    dists = []
    for dist in metadata.distributions():
        name = dist.metadata.get("Name") or ""
        key = _norm(name)
        if not name or key in seen or key in BUILD_ONLY or key in SELF:
            continue
        seen.add(key)
        dists.append(dist)
    dists.sort(key=lambda d: _norm(d.metadata["Name"]))

    out = [
        "# Third-party notices for PoseCraft\n",
        "PoseCraft is MIT-licensed (see LICENSE). The packaged app also contains the software "
        "listed below, each under its own license. This file is generated by "
        "`scripts/third_party_notices.py`; edit that script, not this file.\n",
        "## Summary\n",
        "| Component | Version | License |",
        "|---|---|---|",
    ]
    for dist in dists:
        out.append(f"| {dist.metadata['Name']} | {dist.version} | {_license_name(dist)} |")
    out.append(f"| Python | {sys.version.split()[0]} | PSF-2.0 |")
    out.append("")
    if EXTRA.strip():
        out += ["## Components not installed from pip\n", EXTRA.strip(), ""]

    out.append("## Python runtime\n")
    python_license = Path(sys.base_prefix) / "LICENSE.txt"
    if python_license.is_file():
        out.append(_block(python_license.read_text(encoding="utf-8", errors="replace").strip()))
    else:
        out.append("The Python Software Foundation License: https://docs.python.org/3/license.html\n")

    out.append("## Python packages\n")
    for dist in dists:
        name = dist.metadata["Name"]
        out.append(f"### {name} {dist.version}\n")
        out.append(f"License: {_license_name(dist)}" + (f"  \nHome page: {_homepage(dist)}" if _homepage(dist) else "") + "\n")
        texts = _license_texts(dist)
        if not texts:
            out.append("No license text ships in this package's metadata; see its home page.\n")
        for filename, text in texts:
            out.append(f"{filename}:\n")
            out.append(_block(text))

    OUTPUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT} ({len(dists)} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
